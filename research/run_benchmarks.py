"""
Backtest the Stage E benchmarks on the research and validation periods.

Writes research/trials/benchmarks.md and benchmarks.json. Benchmarks are
reference points, not trials, so they are not added to the trial log.

Usage (from the repo root):
    python -m research.run_benchmarks
"""

from __future__ import annotations

import json
from pathlib import Path

from research.data.loader import load_panel
from research.data.splits import PERIODS
from research.engine import settings
from research.engine.backtest import run_backtest
from research.strategies import BENCHMARKS
from shared.universe import SURVIVORSHIP_NOTE

OUT_DIR = Path(__file__).resolve().parent / "trials"
BASELINE = "buy_hold_index"
EQUAL_WEIGHT = "equal_weight_universe"


def run_all(panel=None) -> dict:
    panel = panel or load_panel()
    results = {}
    for name, cls in BENCHMARKS.items():
        strat = cls()
        results[name] = {"params": strat.params(), "periods": {}}
        for period, (start, end) in PERIODS.items():
            results[name]["periods"][period] = run_backtest(strat, panel, start, end).metrics
    for name in results:
        for period in PERIODS:
            m, b = results[name]["periods"][period], results[BASELINE]["periods"][period]
            m["excess_cagr_vs_buy_hold"] = m["cagr"] - b["cagr"]
            m["excess_cagr_vs_equal_weight"] = m["cagr"] - results[EQUAL_WEIGHT]["periods"][period]["cagr"]
    return results


def to_markdown(results: dict) -> str:
    pct = lambda x: f"{x:+.1%}" if x is not None else ""
    lines = [
        "# Stage E benchmarks",
        "",
        "Generated by `python -m research.run_benchmarks`. Research and validation periods only; "
        "holdout is locked.",
        "",
        f"Costs: {settings.FEE_BPS:g} bp fee + {settings.SLIPPAGE_BPS:g} bp slippage per side. "
        "Signals at the close, fills at the next open. Long-only, cash only. Returns include dividends.",
        "",
        f"**Caveat:** {SURVIVORSHIP_NOTE}",
        "",
    ]
    for period, (start, end) in PERIODS.items():
        lines += [
            f"## {period.capitalize()} ({start.date()} to {end.date()})",
            "",
            "| Strategy | CAGR after costs | vs buy-and-hold | vs equal-weight | Max drawdown | Volatility | Sharpe (rf=0) | Turnover/yr (one-way) | Cost drag/yr |",
            "|---|---:|---:|---:|---:|---:|---:|---:|---:|",
        ]
        for name, r in results.items():
            m = r["periods"][period]
            lines.append(
                f"| {name} | {pct(m['cagr'])} | {pct(m['excess_cagr_vs_buy_hold'])} | {pct(m['excess_cagr_vs_equal_weight'])} | "
                f"{m['max_drawdown']:.1%} | {m['ann_vol']:.1%} | {m['sharpe_rf0']:.2f} | "
                f"{m['turnover_one_way_per_year']:.0%} | {m['cost_drag_per_year']:.2%} |")
        lines.append("")
    lines += [
        "**How to read this:** the universe is today's winners, so beating buy-and-hold SPY proves "
        "little. A stock-picking idea has to beat `equal_weight_universe` (simply owning all the same "
        "stocks) to show real skill.",
        "",
        "## Settings", ""]
    for name, r in results.items():
        lines.append(f"- `{name}`: {r['params']}")
    return "\n".join(lines) + "\n"


if __name__ == "__main__":
    res = run_all()
    (OUT_DIR / "benchmarks.json").write_text(json.dumps(res, indent=2))
    md = to_markdown(res)
    (OUT_DIR / "benchmarks.md").write_text(md, encoding="utf-8")
    print(md)
